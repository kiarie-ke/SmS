export interface PaginationMeta {
  page: number;
  limit: number;
  total: number;
  totalPages: number;
}

export interface ApiSuccess<T> {
  success: true;
  data: T;
  meta?: PaginationMeta;
}

export interface ApiError {
  success: false;
  error: {
    code: string;
    message: string;
    details?: unknown;
  };
}

/** A service may return this shape to add pagination metadata to the envelope. */
export interface PaginatedResult<T> {
  data: T[];
  meta: PaginationMeta;
}
